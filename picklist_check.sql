-- 1. Code - TDI Select: any short, blank or space-padded values?
--    Only "[ ]" or "[  ]" rows (blanks) = fine. "[ 5]" = padded. "[5]" = stored without the leading zero.
SELECT '[' || CCNIPSELECTCD || ']' AS val,
       LENGTH(CCNIPSELECTCD)       AS len,
       COUNT(*)                    AS cnt
  FROM EVIEW_MV
 WHERE TRIM(CCNIPSELECTCD) IS NULL
    OR LENGTH(TRIM(CCNIPSELECTCD)) < 2
    OR CCNIPSELECTCD <> TRIM(CCNIPSELECTCD)
 GROUP BY CCNIPSELECTCD
 ORDER BY 1;

